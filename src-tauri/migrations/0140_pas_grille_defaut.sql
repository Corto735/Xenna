-- ============================================================
-- PRÉLÈVEMENT À LA SOURCE — grilles de taux par défaut (métropole)
--
-- Art. 204 H, III du CGI : à défaut de taux personnalisé transmis par
-- l'administration, l'employeur applique le taux de la grille correspondant
-- à la base mensuelle de prélèvement. Ce taux est UNIQUE : il s'applique à
-- la TOTALITÉ de la base, ce n'est pas un barème progressif par tranches.
--
-- Une ligne = une plage de la grille : taux applicable si
-- borne_min ≤ base < borne_max (borne_max NULL = dernière plage).
-- Dates de fin exclusives (cf. 0136).
--
-- Zone : métropole et hors de France (I. du BOFiP). Les grilles de
-- Guadeloupe/Martinique/La Réunion et de Guyane/Mayotte ne sont pas
-- reprises : le simulateur ne connaît pas le domicile fiscal du salarié.
--
-- Périodes d'application (BOFiP, BOI-BAREME-000037, versions citées) :
--   2019 à 2024 : grille de l'année, au 1er janvier (lois de finances pour
--                 2020, 2021, 2022, 2023, 2024, art. 2) ;
--   la grille 2024 reste applicable jusqu'au 30/04/2025 : celle de 2025
--                 ne s'applique qu'« à compter du 1er mai 2025 »
--                 (loi n° 2025-127 du 14 février 2025, art. 2) ;
--   la grille 2025 reste applicable jusqu'au 30/04/2026 : celle de 2026
--                 s'applique « à compter du 1er mai 2026 » (BOFiP du
--                 07/04/2026, inchangée dans la version du 06/07/2026).
-- Avant le 01/01/2019 le prélèvement à la source n'existait pas : aucune
-- grille, aucun PAS sur le bulletin.
-- Hors champ : l'abattement des contrats courts (CDD ≤ 2 mois).
-- ============================================================
CREATE TABLE IF NOT EXISTS pas_grille_defaut (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    zone        TEXT NOT NULL DEFAULT 'METROPOLE',
    date_debut  TEXT NOT NULL,
    date_fin    TEXT,
    borne_min   TEXT NOT NULL,
    borne_max   TEXT,
    taux        TEXT NOT NULL,
    source      TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_pas_grille_date ON pas_grille_defaut (zone, date_debut);


